const pool = new Pool({ connectionString: env.POSTGRES_URL });

(async () => {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    await client.query('CREATE SEQUENCE IF NOT EXISTS creative_workshops_id_seq');

    await client.query(`
      CREATE TABLE IF NOT EXISTS creative_workshops (
        id bigint NOT NULL DEFAULT nextval('creative_workshops_id_seq'::regclass),
        created_at timestamptz NOT NULL DEFAULT now(),
        name varchar NOT NULL,
        price numeric NOT NULL,
        description text,
        age text,
        image_path text,
        schedule text[] NOT NULL DEFAULT '{}'::text[],
        sort_order integer NOT NULL DEFAULT 0,
        is_active boolean NOT NULL DEFAULT true,
        CONSTRAINT creative_workshops_pkey PRIMARY KEY (id)
      )
    `);

    await client.query(
      'ALTER SEQUENCE creative_workshops_id_seq OWNED BY creative_workshops.id'
    );

    const { rows: countRows } = await client.query(
      'SELECT COUNT(*)::int AS n FROM creative_workshops'
    );
    const n = countRows[0].n;
    if (n > 0) {
      console.log(`Table already has ${n} rows, skip insert`);
    } else {
      for (const card of CARDS) {
        await client.query(
          `
          INSERT INTO creative_workshops
            (name, price, description, age, image_path, schedule, sort_order, is_active)
          VALUES
            ($1, $2, $3, $4, $5, $6::text[], $7, true)
          `,
          [
            card.name,
            card.price,
            card.description,
            card.age,
            card.image_path,
            card.schedule,
            card.sort_order,
          ]
        );
      }
      console.log(`Inserted ${CARDS.length} rows`);
    }

    await client.query('COMMIT');

    const { rows } = await client.query(`
      SELECT id, name, price, age, image_path, schedule, sort_order, is_active
      FROM creative_workshops
      ORDER BY sort_order ASC, id ASC
    `);
    console.log(JSON.stringify(rows, null, 2));
  } catch (e) {
    try {
      await client.query('ROLLBACK');
    } catch {
      // ignore rollback errors
    }
    throw e;
  } finally {
    client.release();
    await pool.end();
  }
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
